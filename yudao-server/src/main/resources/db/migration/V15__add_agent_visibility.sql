-- ============================================================
-- V15: 智能体新增 visibility —— 可见性（0=个人 / 1=公开）
--
-- 背景：C 端「水利智囊 - 智能体」页签需要公开展示当前用户创建的智能体，
--       供同租户其他用户查看与关注。参考 ai_skill_meta.visibility 语义。
--
-- 说明：
--   * 一次性结构变更（不可重复执行）。
--   * 0=个人（默认）：仅创建者可管理/编辑；不出现在智囊公开展示中。
--   * 1=公开：同租户其他用户可在水利智囊查看并关注（编辑/删除仍仅创建者）。
--   * 存量数据默认置 0（个人），不会暴露已有智能体。
-- ============================================================

ALTER TABLE `ai_agent`
    ADD COLUMN `visibility` tinyint NOT NULL DEFAULT 0 COMMENT '可见性: 0=个人, 1=公开';
